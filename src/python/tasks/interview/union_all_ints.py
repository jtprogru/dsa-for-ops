"""Задача (union of all arrays): дано произвольное число массивов целых чисел.

Найти: их объединение — каждое число входит в ответ ровно один раз,
результат отсортирован по возрастанию. Массивы могут быть пустыми или None
(в Go-формулировке — nil-срезы), при пустом входе ответ — пустой список.

Пример:
    [1, 2, 3], [3, 4], [2, 5] -> [1, 2, 3, 4, 5]
    (без аргументов)          -> []
    None, [1, 1, 2]           -> [1, 2]

Закрепляет: lab05 (хеш-таблица). Множество собирает уникальные значения за
один проход по всем массивам — это union из теории множеств. Вариадическая
сигнатура повторяет Go-оригинал `UnionAllInts(slices ...[]int)`.
Сложность: O(n + k log k) время (n — всего элементов, k — уникальных),
O(k) память.
"""


def union_all_ints(*arrays: list[int] | None) -> list[int]:
    seen: set[int] = set()
    for arr in arrays:
        seen.update(arr or ())
    return sorted(seen)
